import React from "react";
import { AlertCircle, Loader, Terminal } from "lucide-react";

type CodeAnalysisResultProps = {
  code: string | undefined;
  status: "executing" | "inProgress" | "complete";
  result: string | undefined;
};

/** Formato devolvido por run_python_analysis (agent/imdb/python_sandbox.py). */
type AnalysisOutput = {
  text: string;
  image_id: string | null;
  is_error: boolean;
};

function parseAnalysisResult(result: string | undefined): AnalysisOutput | null {
  if (!result) return null;
  try {
    const parsed = JSON.parse(result);
    if (typeof parsed?.text === "string") return parsed as AnalysisOutput;
  } catch {
    // Não é JSON: mostra o texto como veio.
  }
  return { text: result, image_id: null, is_error: false };
}

/**
 * Mostra o código que o agente rodou (`run_python_analysis`), a saída em texto
 * e, se o código desenhou uma figura, a imagem. A imagem é estática (PNG): o
 * navegador a busca em /api/analysis-images/<id>, que repassa ao agente Python.
 */
export function CodeAnalysisResult({
  code,
  status,
  result,
}: CodeAnalysisResultProps) {
  const output = parseAnalysisResult(result);
  const running = status === "executing" || status === "inProgress";

  return (
    <div className="bg-white dark:bg-gray-800 p-3 rounded-lg border border-gray-200 dark:border-gray-700 shadow-sm">
      <div className="flex items-center gap-2 mb-2">
        <Terminal className="h-4 w-4 text-indigo-500" />
        <h3 className="text-sm font-medium">Ad-hoc analysis</h3>
      </div>

      {code && (
        <pre className="text-xs bg-gray-50 dark:bg-gray-900 rounded-md p-2 mb-2 overflow-x-auto">
          <code>{code}</code>
        </pre>
      )}

      {running && (
        <div className="flex items-center gap-2 text-xs text-indigo-500">
          <Loader className="h-3 w-3 animate-spin" />
          <span>Running...</span>
        </div>
      )}

      {status === "complete" && output && (
        <>
          <pre
            className={`text-xs whitespace-pre-wrap overflow-x-auto rounded-md p-2 ${
              output.is_error
                ? "bg-red-50 text-red-700 dark:bg-red-950/30 dark:text-red-300"
                : "bg-gray-50 dark:bg-gray-900 text-gray-800 dark:text-gray-200"
            }`}
          >
            {output.is_error && (
              <span className="inline-flex items-center gap-1 font-medium">
                <AlertCircle className="h-3 w-3" /> Error
                {"\n"}
              </span>
            )}
            {output.text}
          </pre>
          {output.image_id && (
            // Imagem estática; <img> simples basta (sem otimização do Next).
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={`/api/analysis-images/${output.image_id}`}
              alt="Chart generated by the analysis"
              className="mt-2 max-w-full rounded-md border border-gray-200"
            />
          )}
        </>
      )}

      {status === "complete" && !output && (
        <p className="text-sm text-gray-500">No output was returned.</p>
      )}
    </div>
  );
}
